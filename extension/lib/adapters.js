const t = ir => H[ir.meta.language === 'en' ? 'en' : 'ja'];
const cell = s => String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const yamlStr = s => JSON.stringify(String(s || '').replace(/\s+/g, ' ').trim());
const tomlStr = s => JSON.stringify(String(s));
const bullets = list => list.map(x => `- ${x}`).join('\n');

function section(title, body) {
  return body && body.trim() ? `## ${title}\n\n${body.trim()}\n` : '';
}

// ---------- 指示ファイル（CLAUDE.md / AGENTS.md） ----------
export function renderInstructions(ir, target) {
  const L = t(ir);
  const parts = [];
  parts.push(`# ${ir.meta.name}\n`);
  if (ir.meta.summary) parts.push(`${ir.meta.summary}\n`);

  const ov = [];
  if (ir.overview.purpose) ov.push(ir.overview.purpose);
  if (ir.overview.deliverables.length) ov.push(`${L.deliverables}:\n${bullets(ir.overview.deliverables)}`);
  if (ir.overview.audience) ov.push(`${L.audience}: ${ir.overview.audience}`);
  parts.push(section(L.purpose, ov.join('\n\n')));

  const env = [];
  if (ir.context.techStack.length) env.push(`${L.tech}: ${ir.context.techStack.join(', ')}`);
  if (ir.context.structure) env.push(ir.context.structure);
  if (ir.context.commands.length) {
    env.push(`### ${L.commands}\n\n${L.cmdHead}\n| --- | --- | --- |\n${ir.context.commands.map(c => `| ${cell(c.name)} | \`${cell(c.command)}\` | ${cell(c.description)} |`).join('\n')}`);
  }
  parts.push(section(L.env, env.join('\n\n')));

  if (ir.rules.length) {
    const groups = new Map();
    for (const r of ir.rules) {
      const k = r.category || '';
      if (!groups.has(k)) groups.set(k, []);
      groups.get(k).push(r);
    }
    const body = [...groups].map(([cat, rs]) => {
      const lines = rs.map(r => `- ${r.rule}${r.reason && !r.team ? `（${r.reason}）` : ''}`).join('\n');
      return cat ? `### ${cat}\n\n${lines}` : lines;
    }).join('\n\n');
    parts.push(section(L.rules, body));
  }

  const pro = ir.prohibitions.map(p => `- ${p.rule}${p.reason ? `（${p.reason}）` : ''}`);
  if (ir.permissions.denyPaths.length) pro.push(`- ${L.denyPaths}: ${ir.permissions.denyPaths.map(p => `\`${p}\``).join(', ')}`);
  if (ir.permissions.denyCommands.length) pro.push(`- ${L.denyCommands}: ${ir.permissions.denyCommands.map(p => `\`${p}\``).join(', ')}`);
  parts.push(section(L.prohibitions, pro.join('\n')));

  if (ir.workflows.length) {
    const lead = target === 'claude' ? L.skillsLeadClaude : L.skillsLeadCodex;
    parts.push(section(L.skills, `${lead}\n\n${ir.workflows.map(w => `- \`${w.id}\`（${w.name}）: ${w.description}`).join('\n')}`));
  }

  if (ir.roles.length) {
    if (target === 'claude') {
      parts.push(section(L.roles, `${L.rolesLeadClaude}\n\n${ir.roles.map(r => `- \`${r.id}\`（${r.name}）: ${r.description}`).join('\n')}`));
    } else {
      // Codex にはサブエージェントのファイル形式がないため、役割を指示ファイル内に書く
      const body = ir.roles.map(r => {
        const sub = [`### ${r.name}（${r.id}）`, '', `${L.whenToUse}: ${r.description}`];
        if (r.responsibilities.length) sub.push('', `${L.responsibilities}:`, bullets(r.responsibilities));
        if (r.checklist.length) sub.push('', `${L.checklist}:`, r.checklist.map(c => `- [ ] ${c}`).join('\n'));
        if (r.readOnly) sub.push('', L.readOnlyHowto);
        return sub.join('\n');
      }).join('\n\n');
      parts.push(section(L.roles, `${L.rolesLeadCodex}\n\n${body}`));
    }
  }

  if (ir.verification.length) {
    parts.push(section(L.verification, ir.verification.map(v => `- ${v.name}${v.how ? `: ${v.how}` : ''}`).join('\n')));
  }
  if (ir.cautions.length) {
    parts.push(section(L.cautions, ir.cautions.map(c => `- ${c.pitfall}${c.avoid ? ` → ${c.avoid}` : ''}`).join('\n')));
  }
  if (ir.context.glossary.length) {
    parts.push(section(L.glossary, `${L.glossHead}\n| --- | --- |\n${ir.context.glossary.map(g => `| ${cell(g.term)} | ${cell(g.meaning)} |`).join('\n')}`));
  }
  parts.push(`<!-- ${L.generated} -->\n`);
  return parts.filter(Boolean).join('\n');
}

// ---------- スキル（SKILL.md、両ツール共通の Agent Skills 形式） ----------
export function renderSkill(ir, w) {
  const L = t(ir);
  const out = [
    '---',
    `name: ${w.id}`,
    `description: ${yamlStr(`${w.name}。${w.description}`)}`,
    '---',
    '',
    `# ${w.name}`,
    '',
    w.description,
    '',
  ];
  if (w.inputs.length) out.push(`## ${L.inputs}`, '', bullets(w.inputs), '');
  out.push(`## ${L.steps}`, '', w.steps.map((s, i) => `${i + 1}. ${s}`).join('\n'), '');
  if (w.outputs.length) out.push(`## ${L.outputs}`, '', bullets(w.outputs), '');
  if (w.checks.length) out.push(`## ${L.checks}`, '', w.checks.map(c => `- [ ] ${c}`).join('\n'), '');
  if (w.examples.length) out.push(`## ${L.examples}`, '', bullets(w.examples), '');
  return out.join('\n');
}

// ---------- サブエージェント（Claude Code） ----------
export function renderClaudeAgent(ir, r, def) {
  const L = t(ir);
  const fm = ['---', `name: ${r.id}`, `description: ${yamlStr(`${r.name}。${r.description}`)}`];
  if (r.readOnly && def.readOnlyAgentTools) fm.push(`tools: ${def.readOnlyAgentTools}`);
  fm.push('---', '');
  const body = [L.youAre(r.name), r.description, ''];
  if (r.responsibilities.length) body.push(`## ${L.responsibilities}`, '', bullets(r.responsibilities), '');
  if (r.checklist.length) body.push(`## ${L.checklist}`, '', r.checklist.map(c => `- [ ] ${c}`).join('\n'), '');
  if (r.readOnly) body.push(`## ${L.howto}`, '', L.readOnlyHowto, '');
  body.push(`## ${L.report}`, '', L.reportFormat, '');
  return fm.join('\n') + body.join('\n');
}

// ---------- 権限（Claude Code: settings.json） ----------
function claudePathRule(p) {
  let x = String(p).trim().replace(/\\/g, '/');
  if (!x) return null;
  if (x.endsWith('/')) x += '**';
  if (x.startsWith('/') || x.startsWith('~') || x.startsWith('./') || x.startsWith('**')) return x;
  if (!x.includes('/') && x.includes('*')) return `**/${x}`;
  return `./${x}`;
}

export function renderClaudeSettings(ir, def) {
  const level = def.permissionLevels?.[ir.permissions.level] || {};
  const suffix = def.bashPrefixSuffix || ':*';
  const paths = [...new Set([...(def.alwaysDenyPaths || []), ...ir.permissions.denyPaths])];
  const deny = [];
  for (const p of paths) {
    const rule = claudePathRule(p);
    if (!rule) continue;
    deny.push(`Read(${rule})`, `Edit(${rule})`);
  }
  for (const c of ir.permissions.denyCommands) deny.push(`Bash(${c}${suffix})`);
  const allow = ir.permissions.level === 'strict' ? [] : ir.permissions.allowCommands.map(c => `Bash(${c})`);
  const permissions = { allow, deny: [...new Set(deny)] };
  if (level.ask?.length) permissions.ask = level.ask;
  if (level.defaultMode) permissions.defaultMode = level.defaultMode;
  const settings = {};
  if (def.settingsSchema) settings.$schema = def.settingsSchema;
  settings.permissions = permissions;
  return JSON.stringify(settings, null, 2) + '\n';
}

// ---------- 権限（Codex: config.toml） ----------
export function renderCodexConfig(ir, def) {
  const level = def.permissionLevels?.[ir.permissions.level] || def.permissionLevels?.standard || {};
  const lines = [
    '# Harness Builder で生成',
    `# ${def.configNote || ''}`.trimEnd(),
    '# ファイル単位の禁止は Codex の設定では指定できないため、AGENTS.md の「禁止事項」に書いています。',
    '',
  ];
  if (level.approval_policy) lines.push(`approval_policy = ${tomlStr(level.approval_policy)}`);
  if (level.sandbox_mode) lines.push(`sandbox_mode = ${tomlStr(level.sandbox_mode)}`);
  if (level.sandbox_mode === 'workspace-write') {
    lines.push('', '[sandbox_workspace_write]', `network_access = ${def.networkAccess ? 'true' : 'false'}`);
  }
  return lines.join('\n') + '\n';
}

/**
 * IR からファイル一式を作る。
 * 戻り値: [{ path, content, target: 'claude'|'codex'|'meta', kind }]
 */
export function buildFiles(ir, targetsDef, { targets = ['claude', 'codex'], buildInfo, team } = {}) {
  const files = [];
  const add = (path, content, target, kind) => files.push({ path, content, target, kind });

  if (targets.includes('claude')) {
    const def = targetsDef.targets.claude;
    const p = def.project;
    add(p.instructionFile, renderInstructions(ir, 'claude'), 'claude', 'instructions');
    for (const w of ir.workflows) add(`${p.skillsDir}/${w.id}/SKILL.md`, renderSkill(ir, w), 'claude', 'skill');
    for (const r of ir.roles) add(`${p.agentsDir}/${r.id}.md`, renderClaudeAgent(ir, r, def), 'claude', 'agent');
    add(p.settingsFile, renderClaudeSettings(ir, def), 'claude', 'settings');
  }
  if (targets.includes('codex')) {
    const def = targetsDef.targets.codex;
    const p = def.project;
    add(p.instructionFile, renderInstructions(ir, 'codex'), 'codex', 'instructions');
    for (const w of ir.workflows) add(`${p.skillsDir}/${w.id}/SKILL.md`, renderSkill(ir, w), 'codex', 'skill');
    add(p.configFile, renderCodexConfig(ir, def), 'codex', 'settings');
  }

  const meta = targetsDef.metaDir || '.harness';
  add(`${meta}/harness.ir.json`, JSON.stringify(ir, null, 2) + '\n', 'meta', 'ir');
  if (buildInfo) add(`${meta}/build-info.json`, JSON.stringify(buildInfo, null, 2) + '\n', 'meta', 'build-info');
  if (team) add(`${meta}/team-settings.json`, JSON.stringify(team, null, 2) + '\n', 'meta', 'team');
  add(`${meta}/README.md`, renderMetaReadme(ir, targetsDef, targets), 'meta', 'readme');
  return files;
}

function renderMetaReadme(ir, targetsDef, targets) {
  const lines = [
    `# ${ir.meta.name} のハーネス`,
    '',
    'このフォルダの中身は Harness Builder が生成しました。プロジェクトのルートにそのまま配置してください。',
    '',
    '## 含まれるもの',
    '',
  ];
  if (targets.includes('claude')) {
    const p = targetsDef.targets.claude.project;
    lines.push(`- Claude Code: \`${p.instructionFile}\`、\`${p.skillsDir}/\`、\`${p.agentsDir}/\`、\`${p.settingsFile}\``);
  }
  if (targets.includes('codex')) {
    const p = targetsDef.targets.codex.project;
    lines.push(`- Codex: \`${p.instructionFile}\`、\`${p.skillsDir}/\`、\`${p.configFile}\``);
    if (targetsDef.targets.codex.configNote) lines.push(`  - ${targetsDef.targets.codex.configNote}`);
  }
  lines.push(
    '- `.harness/harness.ir.json`: ツールに依存しない中間表現。ハーネスを更新するときの元データです。',
    '- `.harness/build-info.json`: 生成時の入力（資料一覧・モデル名・日時）。',
    '- `.harness/team-settings.json`: 生成に使ったチーム設定（APIキーは含みません）。',
    '',
    '## 共有と更新',
    '',
    '- Gitリポジトリにコミットするか、Box で共有してください。',
    '- 生成された内容は出発点です。実際に使いながら、ルールや手順を手で直して育ててください。',
    '',
  );
  return lines.join('\n');
}
